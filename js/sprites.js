// ---------- renderização ----------
const SPR = (() => {
  const cache = new Map();
  const urlCache = new Map();
  const hex = c => [parseInt(c.slice(1, 3), 16), parseInt(c.slice(3, 5), 16), parseInt(c.slice(5, 7), 16)];
  const RGB = Object.fromEntries(Object.entries(PALETTE).map(([k, v]) => [k, hex(v)]));
  const OUT = hex(PALETTE['0']);
  const INK = '#22170e';

  // "nome@talk" usa as linhas de boca aberta definidas em def.talk.
  function grid(name) {
    const [base, variant] = name.split('@');
    const def = ART[base];
    if (!def) return null;
    def._grids = def._grids || {};
    if (def._grids[name]) return def._grids[name];
    let rows = def.rows.replace(/^\n+|\n+$/g, '').split('\n');
    if (variant && def[variant]) rows = rows.map((r, i) => def[variant][i] ?? r);
    if (def.mirror) rows = rows.map(r => r + [...r].reverse().join(''));
    const w = Math.max(...rows.map(r => r.length));
    return (def._grids[name] = { w, h: rows.length, rows: rows.map(r => r.padEnd(w, '.')) });
  }
  const defOf = name => ART[name.split('@')[0]];

  // Ruído estável por pixel (para apagar o rosto da carta e corromper criaturas).
  const hash = (x, y, s) => { let n = x * 374761393 + y * 668265263 + s * 2147483647; n = (n ^ (n >>> 13)) * 1274126177; return ((n ^ (n >>> 16)) >>> 0) / 4294967296; };

  // opt.ink: desenho a tinta, como gravura em madeira. Escuro vira tinta sólida, meio-tom vira hachura, claro vira papel.
  function build(name, opt = {}) {
    const g = grid(name);
    if (!g) return null;
    const def = defOf(name);
    const pad = def.noOutline || def.ink ? 0 : 1;
    const W = g.w + pad * 2, H = g.h + pad * 2;
    const cv = document.createElement('canvas');
    cv.width = W; cv.height = H;
    const ctx = cv.getContext('2d');
    const img = ctx.createImageData(W, H);
    const d = img.data;
    const at = (x, y) => (x < 0 || y < 0 || x >= g.w || y >= g.h) ? '.' : g.rows[y][x];
    const seed = name.length * 31 + (opt.seed || 0);
    const inkRGB = hex(opt.inkColor || INK);
    const useInk = def.ink || opt.ink;
    for (let y = 0; y < g.h; y++) for (let x = 0; x < g.w; x++) {
      const ch = at(x, y);
      if (ch === '.') continue;
      let [r, gg, b] = RGB[ch] || OUT;
      if (useInk) {
        if (opt.erase > 0 && hash(x, y, 7) < opt.erase) continue;
        // Quatro tons de tinta, como uma gravura: sólido, escuro, médio e uma aguada clara.
        let mix = 0;
        if (!def.ink && ch !== '0' && ch !== 'e') {
          const L = (r * .3 + gg * .55 + b * .15) / 255;
          // contorno interno: onde duas regiões de cor diferente se encontram
          const lum = c => { const v = RGB[c] || OUT; return (v[0] * .3 + v[1] * .55 + v[2] * .15) / 255; };
          const nb = [at(x + 1, y), at(x, y + 1), at(x - 1, y), at(x, y - 1)].filter(c => c !== '.' && c !== ch);
          const line = nb.some(c => lum(c) < L - .14);
          mix = line || L < .3 ? 0 : L < .48 ? .32 : L < .66 ? .55 : .78;
          if (!line && (x + y) % 5 === 0 && mix >= .55) mix -= .2; // granulado de papel
        }
        [r, gg, b] = [lerp(inkRGB[0], 214, mix), lerp(inkRGB[1], 182, mix), lerp(inkRGB[2], 132, mix)];
      } else {
        if (!def.noShade && ch !== 'e' && ch !== '0') {
          if (at(x, y - 1) === '.') { r += (255 - r) * .16; gg += (255 - gg) * .16; b += (255 - b) * .16; }
          else if (at(x, y + 1) === '.') { r *= .78; gg *= .78; b *= .82; }
        }
        if (opt.corrupt) {
          if (ch === 'e') { [r, gg, b] = [255, 92, 58]; }
          else {
            const l = (r * .3 + gg * .55 + b * .15);
            r = lerp(r, l * .82, .55); gg = lerp(gg, l * .95, .55); b = lerp(b, l * .7, .55);
            const n = hash(x, y, seed);
            if (n < .1) { r = 40; gg = 48; b = 30; } else if (n < .16) { r = 112; gg = 128; b = 58; }
          }
        }
        if (opt.warm) { r = Math.min(255, r * 1.08 + 18); gg = Math.min(255, gg * 1.0 + 8); b = b * .82; }
        if (opt.erase > 0 && hash(x, y, 7) < opt.erase) { const s = 70 + hash(y, x, 3) * 90; r = gg = b = s; }
      }
      const o = ((y + pad) * W + (x + pad)) * 4;
      d[o] = r; d[o + 1] = gg; d[o + 2] = b; d[o + 3] = 255;
    }
    if (pad) {
      const [orr, og, ob] = useInk ? inkRGB : opt.outline ? hex(opt.outline) : OUT;
      const solid = (xx, yy) => at(xx - pad, yy - pad) !== '.';
      const src = new Uint8ClampedArray(d);
      for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
        const o = (y * W + x) * 4;
        if (src[o + 3] || (useInk && solid(x, y))) continue;
        const n = (xx, yy) => xx >= 0 && yy >= 0 && xx < W && yy < H && (useInk ? solid(xx, yy) : src[(yy * W + xx) * 4 + 3]);
        if (n(x - 1, y) || n(x + 1, y) || n(x, y - 1) || n(x, y + 1)) { d[o] = orr; d[o + 1] = og; d[o + 2] = ob; d[o + 3] = 255; }
      }
    }
    ctx.putImageData(img, 0, 0);
    return cv;
  }

  const key = (name, opt) => name + '|' + (opt.corrupt ? 'c' : '') + (opt.warm ? 'w' : '') + (opt.ink ? 'i' : '') + (opt.inkColor || '') + (opt.erase ? 'e' + opt.erase.toFixed(2) : '') + (opt.outline || '');
  function get(name, opt = {}) {
    const k = key(name, opt);
    if (!cache.has(k)) cache.set(k, build(name, opt));
    return cache.get(k);
  }
  function url(name, opt = {}) {
    const k = key(name, opt);
    if (!urlCache.has(k)) { const c = get(name, opt); urlCache.set(k, c ? c.toDataURL() : ''); }
    return urlCache.get(k);
  }
  function size(name) { const g = grid(name), def = defOf(name); const pad = def?.noOutline || def?.ink ? 0 : 2; return g ? { w: g.w + pad, h: g.h + pad } : { w: 0, h: 0 }; }
  // <img> pixelado com escala inteira.
  function img(name, scale = 3, opt = {}, cls = '') {
    const s = size(name);
    return `<img class="px ${cls}" alt="" draggable="false" src="${url(name, opt)}" width="${s.w * scale}" height="${s.h * scale}">`;
  }
  // Ícone que acompanha o tamanho do texto ao redor.
  function icon(name, cls = '', opt = {}) {
    return `<img class="ico ${cls}" alt="" draggable="false" src="${url(name, opt)}">`;
  }
  return { get, url, img, icon, size, grid };
})();
